from dataclasses import dataclass

from shared.model.model_partition import ModelPartitionId
from shared.plan.partition_replica_id import PartitionReplicaId
from shared.plan.plan_version import PlanVersion
from worker.domain.context.hop_invocation_context import (
    HopInvocationContext,
)
from worker.domain.context.ingress_invocation_context import IngressInvocationContext
from worker.domain.context.model_pass_context import (
    ModelPassContext,
)
from worker.domain.context.partition_invocation_context import (
    PartitionInvocationContext,
)
from worker.domain.plan.hop.hop import SourceHop
from worker.domain.tensor.tensor_bundle import TensorBundle

type SourceInvocationContext = PartitionInvocationContext | IngressInvocationContext


## This is the input to the execution of a successor as generated by a predecessor
@dataclass(frozen=True, slots=True)
class PartitionInvocationContribution:
    source_hop_invocation_context: HopInvocationContext
    target_replica_id: PartitionReplicaId
    bundle: TensorBundle

    @property
    def plan_version(self) -> PlanVersion:
        return self.source_hop_invocation_context.model_pass_context.plan_version

    @property
    def partition_id(self) -> ModelPartitionId:
        return self.target_replica_id.partition_id

    @property
    def model_pass_context(self) -> ModelPassContext:
        return self.source_hop_invocation_context.model_pass_context

    @property
    def source_hop(self) -> SourceHop:
        return self.source_hop_invocation_context.hop


## Acknowledges receipt of a partition invocation contribution.
@dataclass(frozen=True, slots=True)
class PartitionInvocationContributionAck:
    context: SourceInvocationContext
